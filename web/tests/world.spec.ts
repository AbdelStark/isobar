import {test, expect} from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';

test.beforeEach(async ({page}) => {
  page.on('pageerror', error => {throw error;});
  await page.goto('/');
  await expect(page.locator('#scenario')).toHaveValue('world');
});

test('Earth controls, nations and layers follow the filtered replay', async ({page}, info) => {
  await expect(page.locator('#nation-list button')).toHaveCount(8);
  await expect(page.locator('#map-legend')).toContainText('8/8 states on Earth');
  const shape = page.locator('.earth-sphere');
  const original = await page.locator('.earth-country').first().getAttribute('d');
  await page.locator('#world-east').click();
  expect(await page.locator('.earth-country').first().getAttribute('d')).not.toBe(original);
  const normal = await shape.getAttribute('d');
  await page.locator('#world-zoom-in').click();
  expect(await shape.getAttribute('d')).not.toBe(normal);
  await page.locator('#world-reset').click();
  await page.locator('#world-projection').selectOption('map');
  await expect(page.locator('.earth-country.modeled')).toHaveCount(8);
  await page.locator('[data-country="chn"][role="button"]').focus();
  await page.keyboard.press('Enter');
  await expect(page.locator('#selected-nation')).toHaveText('China');
  await expect(page.locator('#nation-chn')).toBeFocused();
  await page.locator('#world-projection').selectOption('globe');
  const earth = page.locator('.earth-canvas > svg');
  const bounds = (await earth.boundingBox())!;
  const beforeDrag = await page.locator('.earth-country.modeled').first().getAttribute('d');
  await page.mouse.move(bounds.x + bounds.width/2, bounds.y + bounds.height/2);
  await page.mouse.down();
  await page.mouse.move(bounds.x + bounds.width/2 + 65, bounds.y + bounds.height/2, {steps: 5});
  await page.mouse.up();
  expect(await page.locator('.earth-country.modeled').first().getAttribute('d')).not.toBe(beforeDrag);
  await page.locator('#world-run').click();
  await expect(page.locator('#status')).toContainText('Run completed');
  await expect(page.locator('#world-play')).toBeEnabled();
  await expect(page.locator('#world-view')).toBeEnabled();
  await expect(page.locator('#world-boundary')).toContainText('PUBLIC RECORD');
  await expect(page.locator('#inspect-decision')).toBeDisabled();
  await expect(page.locator('#nation-inspector')).not.toContainText('Bounded choice');
  await page.clock.install();
  await page.locator('#world-play').click();
  await page.clock.runFor(900);
  await expect(page.locator('#world-tick')).toHaveText('1 / 35');
  await page.locator('#nation-chn').focus();
  await expect(page.locator('#world-play')).toHaveText('Play world');
  await page.clock.runFor(1800);
  await expect(page.locator('#world-tick')).toHaveText('1 / 35');
  await expect(page.locator('#nation-chn')).toBeFocused();
  const share = await page.locator('#nation-chn .nation-share').textContent();
  await page.locator('#world-timeline').focus();
  await page.keyboard.press('End');
  await expect(page.locator('#world-tick')).toHaveText('35 / 35');
  await expect(page.locator('#tick-label')).toHaveText('35 / 35');
  expect(await page.locator('#nation-chn .nation-share').textContent()).not.toBe(share);
  await page.locator('#world-layer').selectOption('gap');
  await expect(page.locator('#map-legend')).toContainText('not a probability');
  await page.locator('#world-layer').selectOption('service');
  await expect(page.locator('#map-legend')).toContainText('Cumulative service');
  await page.locator('#world-relations').selectOption('beliefs');
  await expect(page.locator('.earth-link.beliefs')).toHaveCount(0);
  await page.locator('#inspect-observations').click();
  await expect(page.locator('#world-view')).toHaveValue('chn');
  await expect(page.locator('.earth-link.beliefs')).toHaveCount(7);
  await expect(page.locator('#nation-inspector')).toContainText('Bounded choice');
  await expect(page.locator('#inspect-decision')).toBeEnabled();
  await page.locator('#world-explorer').screenshot({path: info.outputPath('earth-observations.png')});
  await page.locator('#world-edit').click();
  await expect(page.locator('#scenario')).toBeFocused();
  await page.locator('#scenario').selectOption('s2');
  await expect(page.locator('#map-legend')).toContainText('fictional actors');
  await expect(page.locator('#world-tick')).toHaveText('SETUP');
});

test('decision inspector respects privacy, recovers from failures and explains interventions', async ({page}) => {
  await page.locator('#nation-usa').click();
  await page.locator('#world-run').click();
  await expect(page.locator('#status')).toContainText('Run completed');
  await page.locator('#inspect-observations').click();
  await expect(page.locator('#world-view')).toHaveValue('usa');
  await page.route('**/api/decision', route => route.abort());
  await page.locator('#inspect-decision').click();
  await expect(page.locator('#decision-analysis')).toContainText('not reachable');
  await page.unroute('**/api/decision');
  await page.locator('#inspect-decision').click();
  await expect(page.locator('#decision-analysis')).toContainText('Decision at tick 0');
  await expect(page.locator('#decision-analysis')).toContainText('not welfare or an equilibrium');
  await expect(page.locator('#decision-analysis svg circle')).toHaveCount(6);
  await page.locator('#world-timeline').focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.locator('#decision-analysis')).toBeEmpty();
  await page.locator('#world-intervene').click();
  await expect(page.locator('#branch-actor')).toHaveValue('usa');
  await expect(page.locator('#branch-actor')).toBeFocused();
  await page.locator('#branch-run').click();
  await expect(page.locator('#status')).toContainText('Branch complete');
  await page.locator('#inspect-decision').click();
  await expect(page.locator('#decision-analysis')).toContainText('Recorded override');
  await expect(page.locator('#decision-analysis')).toContainText('Train 0.2');
  await page.locator('#world-view').selectOption('public');
  await expect(page.locator('#world-view')).toHaveValue('public');
  await expect(page.locator('#inspect-decision')).toBeDisabled();
  await expect(page.locator('#decision-analysis')).toBeEmpty();
  await expect(page.locator('#nation-inspector')).not.toContainText('Myopic choice');
  await page.locator('#world-view').selectOption('truth');
  await expect(page.locator('#world-boundary')).toContainText('POST-RUN TRUTH');
  await page.locator('#nation-chn').click();
  await page.locator('#inspect-decision').click();
  await expect(page.locator('#decision-analysis')).toContainText('Decision at tick 1');
  await page.getByText('Payoff components and choice probabilities', {exact: true}).click();
  await expect(page.getByRole('table', {name:'Decision payoff alternatives'})).toBeVisible();
});

